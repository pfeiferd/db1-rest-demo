package demo;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import javax.sql.DataSource;

import org.h2.jdbcx.JdbcDataSource;

/** Legt eine Datenbank im Hauptspeicher (H2) mit der Tabelle person an. */
public final class DemoDatabase {
  private DemoDatabase() {
  }

  public static DataSource create() {
    JdbcDataSource ds = new JdbcDataSource();
    // DB_CLOSE_DELAY=-1: Die Datenbank lebt, solange der Server läuft
    ds.setURL("jdbc:h2:mem:demo;DB_CLOSE_DELAY=-1");
    try (Connection c = ds.getConnection(); Statement st = c.createStatement()) {
      st.execute("DROP TABLE IF EXISTS person");
      st.execute("CREATE TABLE person ("
          + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
          + " first_name VARCHAR(40) NOT NULL,"
          + " last_name VARCHAR(40) NOT NULL)");
      st.execute("INSERT INTO person (first_name, last_name) VALUES"
          + " ('Ada', 'Lovelace'), ('Alan', 'Turing'), ('Grace', 'Hopper')");
    } catch (SQLException e) {
      throw new IllegalStateException(e);
    }
    return ds;
  }
}
